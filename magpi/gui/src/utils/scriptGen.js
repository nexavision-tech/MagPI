export const generatePythonScript = (nodes, connections, crs, processingScope) => {
    let script = `# Generated by MagPI Canvas (v0.1.0 Alpha)\n`;
    script += `import magpi as arcpy\n`;
    script += `import os\n\n`;
    
    script += `# --- Global Environment ---\n`;
    script += `arcpy.env.workspace = "./tmp_wksp"\n`;
    
    // Format CRS safely whether it's "EPSG:4326" or just "4326"
    const crsValue = crs.includes(':') ? crs.split(':')[1] : `"${crs}"`;
    script += `arcpy.env.outputCoordinateSystem = ${crsValue}\n`;
    script += `arcpy.env.overwriteOutput = True\n\n`;
    
    script += `arcpy.AddMessage("Initiating MagPI Visual Model execution...")\n\n`;
    
    // Generate variable names map based on node IDs so wires connect correctly
    const varMap = {};
    nodes.forEach((n, idx) => { 
        varMap[n.id] = `${n.toolId.split('_').pop()}_${idx+1}`; 
    });

    // Write the actual pipeline logic
    nodes.forEach((n) => {
        let funcCall = "";
        const p = n.params || {};
        const outVar = varMap[n.id];
        
        // Find what feeds INTO this node
        const incomingCx = connections.find(c => c.to === n.id);
        const inVar = incomingCx ? varMap[incomingCx.from] : 'None';

        if (n.toolId === 'load_raster') {
            funcCall = `${outVar} = arcpy.Raster("${p.file_path}")`;
        }
        else if (n.toolId === 'load_vector') {
            funcCall = `${outVar} = "${p.file_path}"`;
        }
        else if (n.toolId === 'ia_ndvi') {
            funcCall = `${outVar} = arcpy.ia.NDVI(${inVar}, nir_band_id=${p.nir_band}, red_band_id=${p.red_band})`;
        }
        else if (n.toolId === 'ia_export_dl') {
            funcCall = `${outVar} = arcpy.ia.ExportTrainingDataForDeepLearning(getattr(${inVar}, 'name', ${inVar}), "${p.out_folder}", tile_size_x=${p.tile_size}, tile_size_y=${p.tile_size}, stride_x=${p.stride}, stride_y=${p.stride}, shuffle_chips=${p.shuffle ? 'True' : 'False'})`;
        }
        else if (n.toolId === 'ai_detect') {
            funcCall = `${outVar} = arcpy.geoai.DetectObjectsUsingDeepLearning(getattr(${inVar}, 'name', ${inVar}), "${p.out_shp}", "${p.model}")`;
        }
        else if (n.toolId === 'mgt_clip') {
            funcCall = `extent_poly = arcpy.Extent(${p.xmin}, ${p.ymin}, ${p.xmax}, ${p.ymax})\n${outVar} = arcpy.management.Clip(${inVar}, extent_poly, "aoi_clip.shp")`;
        }
        else if (n.toolId === 'mgt_buffer') {
            funcCall = `${outVar} = arcpy.analysis.Buffer(${inVar}, "out_buf.shp", "${p.distance}")`;
        }
        else {
            funcCall = `# Execute ${n.name}`;
        }
        
        if(funcCall) script += `${funcCall}\n`;
    });
    
    // Wrap in Airflow DAG if remote execution is selected
    if (processingScope === "Apache Airflow") {
        const indentedScript = script.split('\n').map(line => '        ' + line).join('\n');
        script = `from airflow.decorators import dag, task\nfrom datetime import datetime\n\n@dag(start_date=datetime(2026, 1, 1), schedule=None)\ndef magpi_pipeline():\n    @task\n    def run_magpi():\n${indentedScript}\n\n    run_magpi()\nmagpi_pipeline()`;
    }
    
    return script;
};