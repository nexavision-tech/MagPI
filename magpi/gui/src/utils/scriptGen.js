import { generateAirflowDAG } from './airflowGen';

export const generatePythonScript = (nodes, connections, crs, processingScope, globalEnv) => {
    if (processingScope === "Apache Airflow") {
        return generateAirflowDAG(nodes, connections, crs, globalEnv);
    }

    let script = `# Generated by MagPI Canvas (v0.1.52 Alpha)\n`;
    script += `import magpi as arcpy\n`;
    script += `import openeo\n`;
    script += `import os\n\n`;
    
    script += `# --- Global Environment ---\n`;
    if (globalEnv) {
        script += `arcpy.env.workspace = "${globalEnv.workspace_dir}"\n`;
        script += `arcpy.env.scratchWorkspace = "${globalEnv.scratch_dir}"\n`;
        script += `arcpy.env.outputWorkspace = "${globalEnv.output_dir}"\n`;
    } else {
        script += `arcpy.env.workspace = "./tmp_wksp"\n`;
    }
    
    const crsValue = crs.includes(':') ? crs.split(':')[1] : `"${crs}"`;
    script += `arcpy.env.outputCoordinateSystem = ${crsValue}\n`;
    const overwriteStr = globalEnv && globalEnv.overwrite_output === false ? "False" : "True";
    script += `arcpy.env.overwriteOutput = ${overwriteStr}\n\n`;
    
    script += `arcpy.AddMessage("Initiating MagPI Visual Model execution...")\n\n`;
    
    const adjList = {};
    const inDegree = {};
    nodes.forEach(n => {
        adjList[n.id] = [];
        inDegree[n.id] = 0;
    });
    
    connections.forEach(c => {
        if (adjList[c.from]) {
            adjList[c.from].push(c.to);
            if (inDegree[c.to] !== undefined) inDegree[c.to]++;
        }
    });

    const queue = [];
    Object.keys(inDegree).forEach(id => {
        if (inDegree[id] === 0) queue.push(id);
    });

    queue.sort((a, b) => nodes.find(n => n.id === a).x - nodes.find(n => n.id === b).x);

    const sortedNodeIds = [];
    while (queue.length > 0) {
        const curr = queue.shift();
        sortedNodeIds.push(curr);
        let neighbors = adjList[curr];
        neighbors.forEach(neighbor => {
            inDegree[neighbor]--;
            if (inDegree[neighbor] === 0) queue.push(neighbor);
        });
    }

    const sortedNodes = sortedNodeIds.map(id => nodes.find(n => n.id === id)).filter(n => n !== undefined);

    const varMap = {};
    sortedNodes.forEach((n, idx) => { 
        varMap[n.id] = `${n.toolId.split('_').pop()}_${idx+1}`; 
    });

    const getProvenance = (nodeId) => {
        const node = nodes.find(n => n.id === nodeId);
        if (!node) return '';
        
        if (['wfs_sentinel2', 'wfs_elevation', 'load_raster'].includes(node.toolId)) return 'raster';
        if (['wfs_nlcd', 'wfs_census', 'load_vector', 'wfs_sciencebase', 'ia_reclassify', 'ai_classify'].includes(node.toolId)) return 'label';
        if (node.toolId === 'core_extent') return 'extent';
        
        const parents = connections.filter(c => c.to === nodeId).map(c => c.from);
        for (let pid of parents) {
            const prov = getProvenance(pid);
            if (prov) return prov;
        }
        return '';
    };

    sortedNodes.forEach((n) => {
        let funcCall = "";
        
        const p = {};
        for (const [key, val] of Object.entries(n.params || {})) {
            p[key] = (val && typeof val === 'object' && ['select', 'date', 'datetime-local'].includes(val.type)) ? val.value : val;
        }

        const outVar = varMap[n.id];
        const incomingCxs = connections.filter(c => c.to === n.id);
        const inNodes = incomingCxs.map(c => nodes.find(src => src.id === c.from));
        
        let inRasterVar = 'None';
        let inLabelVar = 'None';
        let inExtentVars = [];

        const resolveSourceVar = (c) => {
            const baseVar = varMap[c.from];
            const srcNode = nodes.find(src => src.id === c.from);
            
            if (srcNode && srcNode.toolId === 'load_raster' && c.sourceHandle) {
                switch(c.sourceHandle) {
                    case 'path_out': return `getattr(${baseVar}, "catalogPath", getattr(${baseVar}, "name", str(${baseVar})))`;
                    case 'crs': return `${baseVar}.spatialReference`;
                    case 'extent': return `${baseVar}.extent`;
                    case 'bands': return `${baseVar}.bandCount`;
                    case 'dtype': return `${baseVar}.pixelType`;
                    case 'nodata': return `${baseVar}.noDataValues`;
                    case 'acq_date': return `getattr(${baseVar}, "acquisitionDate", None)`;
                    case 'wavelengths': return `getattr(${baseVar}, "wavelengths", None)`;
                    case 'rpc': return `getattr(${baseVar}, "RPC", None)`;
                    case 'raster': return baseVar;
                    default: return baseVar;
                }
            }
            return baseVar;
        };

        incomingCxs.forEach(c => {
            const { from } = c;
            const prov = getProvenance(from);
            const resolvedVar = resolveSourceVar(c);
            
            if (c.sourceHandle === 'extent' || prov === 'extent') {
                inExtentVars.push(resolvedVar);
            }
            else if (prov === 'raster' && c.sourceHandle !== 'extent' && c.sourceHandle !== 'crs' && c.sourceHandle !== 'bands') {
                inRasterVar = resolvedVar;
            }
            else if (prov === 'label') {
                inLabelVar = resolvedVar;
            }
        });

        const inExtentVar = inExtentVars.length > 0 ? inExtentVars[0] : 'None';
        const primaryInVar = incomingCxs.length > 0 ? resolveSourceVar(incomingCxs[0]) : 'None';

        if (n.toolId === 'core_extent') {
            funcCall = `${outVar} = arcpy.Extent(${p.xmin}, ${p.ymin}, ${p.xmax}, ${p.ymax})`;
        }
        else if (n.toolId === 'load_raster') {
            const inPathCx = incomingCxs.find(c => c.targetHandle === 'path_in');
            const inCrsCx = incomingCxs.find(c => c.targetHandle === 'set_crs');
            const inPathVar = inPathCx ? resolveSourceVar(inPathCx) : `"${p.file_path}"`;
            funcCall = `${outVar} = arcpy.Raster(${inPathVar})`;
            
            if (inCrsCx) {
                const inCrsVar = resolveSourceVar(inCrsCx);
                const outName = `"reproj_raster_${n.id.split('_')[1]}.tif"`;
                funcCall += `\narcpy.AddMessage(f"Dynamically reprojecting {${inPathVar}} to match {${inCrsVar}}")`;
                funcCall += `\narcpy.management.ProjectRaster(${outVar}, os.path.join(arcpy.env.scratchWorkspace, ${outName}), ${inCrsVar})`;
                funcCall += `\n${outVar} = arcpy.Raster(os.path.join(arcpy.env.scratchWorkspace, ${outName}))`;
            }
        }
        else if (n.toolId === 'load_vector') {
            const inPathCx = incomingCxs.find(c => c.targetHandle === 'path_in');
            const inCrsCx = incomingCxs.find(c => c.targetHandle === 'set_crs');
            const inPathVar = inPathCx ? resolveSourceVar(inPathCx) : `"${p.file_path}"`;
            funcCall = `${outVar} = ${inPathVar}`;
            
            if (inCrsCx) {
                const inCrsVar = resolveSourceVar(inCrsCx);
                const outName = `"reproj_vector_${n.id.split('_')[1]}.shp"`;
                funcCall += `\narcpy.AddMessage(f"Dynamically reprojecting {${inPathVar}} to match {${inCrsVar}}")`;
                funcCall += `\narcpy.management.Project(${outVar}, os.path.join(arcpy.env.scratchWorkspace, ${outName}), ${inCrsVar})`;
                funcCall += `\n${outVar} = os.path.join(arcpy.env.scratchWorkspace, ${outName})`;
            }
        }
        else if (n.toolId === 'wfs_sentinel2') {
            let extraArgs = "";
            if (p.selected_items) extraArgs += `, item_ids="${p.selected_items}"`;
            if (p.selected_bands) extraArgs += `, bands="${p.selected_bands}"`;
            
            if (inExtentVars.length > 1) {
                const outFileNameBase = `s2_cloud_extract_${n.id.split('_')[1]}`;
                funcCall = `${outVar} = []\nfor i, ext in enumerate([${inExtentVars.join(', ')}]):\n    ${outVar}.append(arcpy.wfs.PullSentinel2(ext, f"${outFileNameBase}_{i}.tif", max_cloud_cover=${p.max_cloud_cover}, date_range="${p.start_date}/${p.end_date}"${extraArgs}))`;
            } else {
                const outFileName = `s2_cloud_extract_${n.id.split('_')[1]}.tif`;
                funcCall = `${outVar} = arcpy.wfs.PullSentinel2(${inExtentVar}, "${outFileName}", max_cloud_cover=${p.max_cloud_cover}, date_range="${p.start_date}/${p.end_date}"${extraArgs})`;
            }
        }
        else if (n.toolId === 'wfs_copernicus') {
            if (inExtentVars.length > 1) {
                const outFileNameBase = `copernicus_extract_${n.id.split('_')[1]}`;
                funcCall = `${outVar} = []\nfor i, ext in enumerate([${inExtentVars.join(', ')}]):\n    ${outVar}.append(arcpy.wfs.PullCopernicusData(ext, f"${outFileNameBase}_{i}.json", collection="${p.collection}", product_type="${p.product_type}", start_date="${p.start_date}", end_date="${p.end_date}", cdse_token="${p.cdse_token}"))`;
            } else {
                const outFileName = `copernicus_extract_${n.id.split('_')[1]}.json`;
                funcCall = `${outVar} = arcpy.wfs.PullCopernicusData(${inExtentVar}, "${outFileName}", collection="${p.collection}", product_type="${p.product_type}", start_date="${p.start_date}", end_date="${p.end_date}", cdse_token="${p.cdse_token}")`;
            }
        }
        else if (n.toolId === 'wfs_elevation') {
            if (inExtentVars.length > 1) {
                const outFileNameBase = `usgs_dem_extract_${n.id.split('_')[1]}`;
                funcCall = `${outVar} = []\nfor i, ext in enumerate([${inExtentVars.join(', ')}]):\n    ${outVar}.append(arcpy.wfs.PullUSGSElevation(ext, f"${outFileNameBase}_{i}.tif"))`;
            } else {
                const outFileName = `usgs_dem_extract_${n.id.split('_')[1]}.tif`;
                funcCall = `${outVar} = arcpy.wfs.PullUSGSElevation(${inExtentVar}, "${outFileName}")`;
            }
        }
        else if (n.toolId === 'wfs_nlcd') {
            if (inExtentVars.length > 1) {
                const outFileNameBase = `nlcd_labels_${n.id.split('_')[1]}`;
                funcCall = `${outVar} = []\nfor i, ext in enumerate([${inExtentVars.join(', ')}]):\n    ${outVar}.append(arcpy.wfs.PullNLCD(ext, f"${outFileNameBase}_{i}.tif", year=${p.year}, product="${p.product}"))`;
            } else {
                const outFileName = `nlcd_labels_${n.id.split('_')[1]}.tif`;
                funcCall = `${outVar} = arcpy.wfs.PullNLCD(${inExtentVar}, "${outFileName}", year=${p.year}, product="${p.product}")`;
            }
        }
        else if (n.toolId === 'wfs_sciencebase') {
            funcCall = `${outVar} = arcpy.wfs.PullScienceBase("${p.item_id}", "${p.out_folder}")`;
        }
        else if (n.toolId === 'wfs_census') {
            const outFileName = `census_tracts_${n.id.split('_')[1]}.shp`;
            funcCall = `${outVar} = arcpy.wfs.GetCensusTracts(${p.state_fips}, ${p.county_fips}, ${p.year}, "${outFileName}")`;
        }
        else if (n.toolId === 'wfs_universal') {
            const outFileName = `global_data_extract_${n.id.split('_')[1]}.shp`;
            funcCall = `${outVar} = arcpy.server.DownloadArcGISRESTFeatureLayer("${p.url}", "${outFileName}")`;
        }
        else if (n.toolId === 'ddd_las_to_raster') {
            const outFileName = `lidar_dem_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.ddd.LasDatasetToRaster(${primaryInVar}, "${outFileName}", value_field="${p.value_field}", sampling_value=${p.sampling_value})`;
        }
        else if (n.toolId === 'ia_ndvi') {
            const inVar = inRasterVar !== 'None' ? inRasterVar : primaryInVar;
            funcCall = `${outVar} = [arcpy.ia.NDVI(r, nir_band_id=${p.nir_band}, red_band_id=${p.red_band}) for r in ${inVar}] if isinstance(${inVar}, list) else arcpy.ia.NDVI(${inVar}, nir_band_id=${p.nir_band}, red_band_id=${p.red_band})`;
        }
        else if (n.toolId === 'ia_pansharpen') {
            const inVar = primaryInVar;
            const baseOutName = `pansharpened_${n.id.split('_')[1]}`;
            funcCall = `${outVar} = [arcpy.ia.Pansharpen(in_raster=r, panchromatic_image=r, out_raster=f"${baseOutName}_{i}.tif", method="${p.method}") for i, r in enumerate(${inVar})] if isinstance(${inVar}, list) else arcpy.ia.Pansharpen(in_raster=${inVar}, panchromatic_image=${inVar}, out_raster="${baseOutName}.tif", method="${p.method}")`;
        }
        else if (n.toolId === 'ia_reclassify') {
            const inVar = primaryInVar;
            const baseOutName = `reclassified_${n.id.split('_')[1]}`;
            funcCall = `${outVar} = [arcpy.ia.Reclassify(in_raster=r, out_raster=f"${baseOutName}_{i}.tif", remap_string="${p.remap_string}") for i, r in enumerate(${inVar})] if isinstance(${inVar}, list) else arcpy.ia.Reclassify(in_raster=${inVar}, out_raster="${baseOutName}.tif", remap_string="${p.remap_string}")`;
        }
        else if (n.toolId === 'ia_export_dl') {
            funcCall = `${outVar} = arcpy.ia.ExportTrainingDataForDeepLearning(in_raster=getattr(${inRasterVar}, 'name', ${inRasterVar}), out_folder="${p.out_folder}", in_class_data=getattr(${inLabelVar}, 'name', ${inLabelVar}), tile_size_x=${p.tile_size}, tile_size_y=${p.tile_size}, stride_x=${p.stride}, stride_y=${p.stride}, shuffle_chips=${p.shuffle ? 'True' : 'False'})`;
        }
        else if (n.toolId === 'ia_raster_math') {
            let varA = 'None';
            let varB = 'None';
            if (inNodes.length > 0) varA = varMap[inNodes[0].id];
            if (inNodes.length > 1) varB = varMap[inNodes[1].id];
            let varBListStr = varB === 'None' ? '[None]' : `${varB} if isinstance(${varB}, list) else [${varB}]`;
            funcCall = `_expr = "${p.expression}"\\n${outVar} = [arcpy.ia.RasterMath(a, b, _expr, f"raster_math_{i}.tif") for i, (a, b) in enumerate(zip(${varA} if isinstance(${varA}, list) else [${varA}], ${varBListStr}))]`;
        }
        else if (n.toolId === 'ai_train') {
            const inFolderStr = primaryInVar !== 'None' ? `getattr(${primaryInVar}, 'output', ${primaryInVar})` : `"${p.in_folder}"`;
            funcCall = `${outVar} = arcpy.geoai.TrainDeepLearningModel(in_folder=${inFolderStr}, out_folder="${p.out_folder}", max_epochs=${p.max_epochs}, batch_size=${p.batch_size}, model_type="${p.model_type}")`;
        }
        else if (n.toolId === 'ai_detect') {
            funcCall = `${outVar} = arcpy.geoai.DetectObjectsUsingDeepLearning(getattr(${primaryInVar}, 'name', ${primaryInVar}), "${p.out_shp}", "${p.model}")`;
        }
        else if (n.toolId === 'ai_classify') {
            funcCall = `${outVar} = arcpy.geoai.ClassifyPixelsUsingDeepLearning(getattr(${primaryInVar}, 'name', ${primaryInVar}), "${p.out_raster}", "${p.model}")`;
        }
        else if (n.toolId === 'mgt_clip') {
            const outFileName = `aoi_clip_${n.id.split('_')[1]}.tif`;
            if (inExtentVar !== 'None') {
                funcCall = `${outVar} = arcpy.management.Clip(${inRasterVar}, ${inExtentVar}, "${outFileName}")`;
            } else {
                funcCall = `extent_poly = arcpy.Extent(${p.xmin}, ${p.ymin}, ${p.xmax}, ${p.ymax})\n${outVar} = arcpy.management.Clip(${inRasterVar}, extent_poly, "${outFileName}")`;
            }
        }
        else if (n.toolId === 'mgt_buffer') {
            funcCall = `${outVar} = arcpy.analysis.Buffer(${primaryInVar}, "out_buf.shp", "${p.distance} ${p.unit || ''}".strip())`;
        }
        else if (n.toolId === 'mgt_project_raster') {
            const baseName = `proj_raster_${n.id.split('_')[1]}`;
            funcCall = `${outVar} = [arcpy.management.ProjectRaster(r, f"${baseName}_{i}.tif", "${p.out_crs}", resampling_type="${p.resampling}") for i, r in enumerate(${inRasterVar})] if isinstance(${inRasterVar}, list) else arcpy.management.ProjectRaster(${inRasterVar}, "${baseName}.tif", "${p.out_crs}", resampling_type="${p.resampling}")`;
        }
        else if (n.toolId === 'mgt_project_vector') {
            const baseName = (p.out_feature_class || `proj_vector_${n.id.split('_')[1]}.shp`).replace('.shp', '');
            funcCall = `${outVar} = [arcpy.management.Project(f, f"${baseName}_{i}.shp", out_coor_system="${p.out_crs}") for i, f in enumerate(${primaryInVar})] if isinstance(${primaryInVar}, list) else arcpy.management.Project(${primaryInVar}, "${baseName}.shp", out_coor_system="${p.out_crs}")`;
        }
        else if (n.toolId === 'mgt_array_index') {
            funcCall = `${outVar} = ${primaryInVar}[${p.index || 0}] if isinstance(${primaryInVar}, list) and len(${primaryInVar}) > ${p.index || 0} else ${primaryInVar}`;
        }
        else if (n.toolId === 'mgt_pyramids') {
            funcCall = `${outVar} = ${primaryInVar}\narcpy.management.BuildPyramidsAndStats(${primaryInVar}, build_pyramids=${p.build_pyramids ? 'True' : 'False'}, calculate_stats=${p.calculate_stats ? 'True' : 'False'})`;
        }
        else if (n.toolId === 'mgt_append_attribute') {
            let vectorVar = 'None', arrayVar = 'None';
            incomingCxs.forEach(c => {
                if (c.targetHandle === 'vector_in') vectorVar = varMap[c.from];
                else if (c.targetHandle === 'array_in') arrayVar = varMap[c.from];
            });
            if (vectorVar === 'None' && inNodes.length > 0) vectorVar = varMap[inNodes[0].id];
            if (arrayVar === 'None' && inNodes.length > 1) arrayVar = varMap[inNodes[1].id];
            
            const outFileName = `appended_vector_${n.id.split('_')[1]}.shp`;
            funcCall = `import geopandas as gpd\n_gdf = gpd.read_file(${vectorVar})\n_gdf["${p.field_name || 'new_field'}"] = ${arrayVar}\n_gdf.to_file("${outFileName}")\n${outVar} = "${outFileName}"`;
        }
        else if (n.toolId === 'conv_raster_to_polygon') {
            funcCall = `${outVar} = arcpy.conversion.RasterToPolygon(in_raster=${primaryInVar}, out_polygon_features="${p.out_polygon_features}", background_value=${p.background_value})`;
        }
        // FIXED: Multi-input resolution logic for the Confusion Matrix
        else if (n.toolId === 'stats_confusion_matrix') {
            let refVar = 'None';
            let predVar = 'None';
            
            incomingCxs.forEach(c => {
                const srcNode = nodes.find(src => src.id === c.from);
                if (!srcNode) return;
                
                // Explicitly check for classified/prediction tools vs ground-truth references
                const isPrediction = ['ai_classify', 'ai_detect'].includes(srcNode.toolId);
                const isReference = ['ia_reclassify', 'wfs_nlcd', 'load_vector'].includes(srcNode.toolId);
                
                if (isPrediction) {
                    predVar = varMap[c.from];
                } else if (isReference) {
                    refVar = varMap[c.from];
                } else {
                    const prov = getProvenance(c.from);
                    if (prov === 'label') refVar = varMap[c.from];
                    else predVar = varMap[c.from];
                }
            });
            
            if (refVar === 'None' && inNodes.length > 0) refVar = varMap[inNodes[0].id];
            if (predVar === 'None' && inNodes.length > 1) predVar = varMap[inNodes[1].id];
            
            funcCall = `${outVar} = arcpy.stats.ComputeConfusionMatrix(in_ground_truth=${refVar}, in_classified=${predVar}, out_table="${p.out_table}")`;
        }
        else if (n.toolId === 'etl_spatial_join') {
            let targetVar = 'None', joinVar = 'None';
            incomingCxs.forEach(c => {
                if (c.targetHandle === 'in1') targetVar = varMap[c.from];
                else if (c.targetHandle === 'in2') joinVar = varMap[c.from];
            });
            if (targetVar === 'None' && inNodes.length > 0) targetVar = varMap[inNodes[0].id];
            if (joinVar === 'None' && inNodes.length > 1) joinVar = varMap[inNodes[1].id];
            
            const outFileName = `spatial_join_${n.id.split('_')[1]}.shp`;
            funcCall = `${outVar} = arcpy.analysis.SpatialJoin(target_features=${targetVar}, join_features=${joinVar}, out_feature_class="${outFileName}", join_operation="${p.join_operation}")`;
        }
        else if (n.toolId === 'etl_field_calc') {
            funcCall = `${outVar} = arcpy.management.CalculateField(in_table=${primaryInVar}, field="${p.field_name}", expression="${p.expression}")`;
        }
        else if (n.toolId && n.toolId.startsWith('logic_math_')) {
            let varA = 'None', varB = 'None';
            incomingCxs.forEach(c => {
                if (c.targetHandle === 'a') varA = varMap[c.from];
                else if (c.targetHandle === 'b') varB = varMap[c.from];
            });
            if (varA === 'None' && inNodes.length > 0) varA = varMap[inNodes[0].id];
            if (varB === 'None' && inNodes.length > 1) varB = varMap[inNodes[1].id];
            
            let op = '+';
            if (n.toolId === 'logic_math_sub') op = '-';
            else if (n.toolId === 'logic_math_mul') op = '*';
            else if (n.toolId === 'logic_math_div') op = '/';
            
            funcCall = `import numpy as np\n_a = np.array(${varA}, dtype=float) if isinstance(${varA}, list) else float(${varA})\n_b = np.array(${varB}, dtype=float) if isinstance(${varB}, list) else float(${varB})\n_res = _a ${op} _b\n${outVar} = _res.tolist() if isinstance(_res, np.ndarray) else _res`;
        }
        else if (n.toolId === 'etl_db_writer') {
            funcCall = `arcpy.conversion.ExportToPostGIS(in_features=${primaryInVar}, connection_string="${p.connection_string}", table_name="${p.table_name}")`;
        }
        else if (n.toolId === 'openeo_authenticate') {
            if (p.method === 'OIDC') {
                funcCall = `${outVar} = openeo.connect("openeo.dataspace.copernicus.eu").authenticate_oidc()`;
            } else if (p.method === 'Basic') {
                funcCall = `${outVar} = openeo.connect("openeo.dataspace.copernicus.eu").authenticate_basic("${p.token.split(':')[0]}", "${p.token.split(':')[1] || ''}")`;
            } else {
                funcCall = `${outVar} = openeo.connect("openeo.dataspace.copernicus.eu")`;
            }
        }
        else if (n.toolId === 'openeo_load_collection') {
            funcCall = `${outVar} = ${primaryInVar}.load_collection("${p.collection}", temporal_extent=["${p.start_date}", "${p.end_date}"], bands=${JSON.stringify(p.bands.split(','))})`;
            if (inExtentVar !== 'None') {
                funcCall += `\n${outVar} = ${outVar}.filter_bbox({"west": ${inExtentVar}.XMin, "south": ${inExtentVar}.YMin, "east": ${inExtentVar}.XMax, "north": ${inExtentVar}.YMax})`;
            }
        }
        else if (n.toolId === 'openeo_train_rf') {
            const inFeaturesStr = inRasterVar !== 'None' ? inRasterVar : primaryInVar;
            const inLabelStr = inLabelVar !== 'None' ? inLabelVar : 'y_train_gdf';
            funcCall = `import json\nX = ${inFeaturesStr}.aggregate_spatial(json.loads(${inLabelStr}.to_json()), reducer="mean")\n${outVar}_ml_model = X.fit_class_random_forest(target=json.loads(${inLabelStr}.to_json()), num_trees=${p.num_trees})\n${outVar} = ${outVar}_ml_model.save_ml_model()\n${outVar}_job = ${outVar}.create_job(title="MagPI OpenEO RF Training", job_options={"executor-memory": "2G"})\n${outVar}_job.start_and_wait()\narcpy.AddMessage(f"OpenEO RF Training completed. Cost: {${outVar}_job.describe()['costs']} credits")`;
        }
        else if (n.toolId === 'openeo_predict') {
            const inCubeStr = inRasterVar !== 'None' ? inRasterVar : primaryInVar;
            const inModelStr = varMap[incomingCxs.find(c => nodes.find(src => src.id === c.from)?.toolId === 'openeo_train_rf')?.from || 'None'];
            funcCall = `${outVar} = ${inCubeStr}.predict_random_forest(model=${inModelStr}, dimension="bands")\n${outVar}_job = ${outVar}.execute_batch(out_format="${p.out_format}", title="MagPI OpenEO Prediction", filename_prefix="${p.prefix}")\n${outVar}_results = ${outVar}_job.get_results()\n${outVar}_results.download_files(arcpy.env.outputWorkspace)`;
        }
        else if (n.toolId === 'envi_band_math') {
            const outFileName = `band_math_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.sa.RasterCalculator(expression="${p.expression}", in_raster=${primaryInVar})\n${outVar}.save("${outFileName}")`;
        }
        else if (n.toolId === 'envi_pca') {
            const outFileName = `pca_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.sa.PrincipalComponents(in_raster_bands=${primaryInVar})\n${outVar}.save("${outFileName}")`;
        }
        else if (n.toolId === 'envi_tasseled_cap') {
            const outFileName = `tasseled_cap_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.sa.TasseledCap(in_raster=${primaryInVar}, sensor="${p.sensor}")\n${outVar}.save("${outFileName}")`;
        }
        else if (n.toolId === 'ml_pytorch_inference') {
            const outFileName = p.out_raster || `prediction_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.ml.PyTorchInference(in_raster=${primaryInVar}, model_script_path="${p.model_script_path}", out_raster="${outFileName}", tile_size=${p.tile_size}, batch_size=${p.batch_size}, device="${p.device}")`;
        }
        else if (n.toolId === 'community_structural_damage_volume') {
            let preDsmVar = 'None', postDsmVar = 'None', preOptVar = 'None', footVar = 'None';
            incomingCxs.forEach(c => {
                if (c.targetHandle === 'pre_dsm') preDsmVar = varMap[c.from];
                else if (c.targetHandle === 'post_dsm') postDsmVar = varMap[c.from];
                else if (c.targetHandle === 'pre_optical') preOptVar = varMap[c.from];
                else if (c.targetHandle === 'footprints') footVar = varMap[c.from];
            });
            
            funcCall = `import sys\nsys.path.append("./magpi_workspace/community_nodes")\nimport bda_volume\nfrom magpi.engine.nodes.registry import NODE_REGISTRY\n\n`;
            funcCall += `damage_node = NODE_REGISTRY["community_structural_damage_volume"]()\n`;
            funcCall += `damage_node.inputs = {"in_pre": ${preDsmVar}, "in_pre_optical": ${preOptVar}, "in_post": ${postDsmVar}, "in_vector": ${footVar}}\n`;
            funcCall += `damage_node.params = {"collapse_threshold_meters": ${p.collapse_threshold_m || -2.5}, "solar_elevation_deg": ${p.solar_elevation_deg || 45.0}}\n`;
            funcCall += `damage_node.execute()\n`;
            funcCall += `${outVar} = damage_node.output.get("classified_vector")`;
        }
        else {
            funcCall = `# Execute ${n.name}`;
        }
        
        if(funcCall) script += `${funcCall}\n`;
    });
    
    return script;
};