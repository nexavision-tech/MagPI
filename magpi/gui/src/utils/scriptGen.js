export const generatePythonScript = (nodes, connections, crs, processingScope) => {
    let script = `# Generated by MagPI Canvas (v0.1.33 Alpha)\n`;
    script += `import magpi as arcpy\n`;
    script += `import os\n\n`;
    
    script += `# --- Global Environment ---\n`;
    script += `arcpy.env.workspace = "./tmp_wksp"\n`;
    
    // Format CRS safely
    const crsValue = crs.includes(':') ? crs.split(':')[1] : `"${crs}"`;
    script += `arcpy.env.outputCoordinateSystem = ${crsValue}\n`;
    script += `arcpy.env.overwriteOutput = True\n\n`;
    
    script += `arcpy.AddMessage("Initiating MagPI Visual Model execution...")\n\n`;
    
    // Sort nodes strictly by X coordinate (Left-to-Right execution)
    const sortedNodes = [...nodes].sort((a, b) => a.x - b.x);

    // Generate variable names map based on sorted node IDs
    const varMap = {};
    sortedNodes.forEach((n, idx) => { 
        varMap[n.id] = `${n.toolId.split('_').pop()}_${idx+1}`; 
    });

    // Write the actual pipeline logic
    sortedNodes.forEach((n) => {
        let funcCall = "";
        
        // Unpack complex UI parameter objects (like dropdowns) into raw values
        const p = {};
        for (const [key, val] of Object.entries(n.params || {})) {
            p[key] = (val && typeof val === 'object' && val.type === 'select') ? val.value : val;
        }

        const outVar = varMap[n.id];
        
        // Find what feeds INTO this node
        const incomingCx = connections.find(c => c.to === n.id);
        const inVar = incomingCx ? varMap[incomingCx.from] : 'None';

        // Core Parameters
        if (n.toolId === 'core_extent') {
            funcCall = `${outVar} = arcpy.Extent(${p.xmin}, ${p.ymin}, ${p.xmax}, ${p.ymax})`;
        }
        // Data Ingestion
        else if (n.toolId === 'load_raster') {
            funcCall = `${outVar} = arcpy.Raster("${p.file_path}")`;
        }
        else if (n.toolId === 'load_vector') {
            funcCall = `${outVar} = "${p.file_path}"`;
        }
        
        // WFS Sovereign Cloud
        else if (n.toolId === 'wfs_sentinel2') {
            const outFileName = `s2_cloud_extract_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.wfs.PullSentinel2(${inVar}, "${outFileName}", max_cloud_cover=${p.max_cloud_cover}, date_range="${p.start_date}/${p.end_date}")`;
        }
        else if (n.toolId === 'wfs_elevation') {
            const outFileName = `usgs_dem_extract_${n.id.split('_')[1]}.tif`;
            funcCall = `${outVar} = arcpy.wfs.PullUSGSElevation(${inVar}, "${outFileName}")`;
        }
        else if (n.toolId === 'wfs_nlcd') {
            const outFileName = `nlcd_labels_${n.id.split('_')[1]}.tif`;
            // Uses the connection from the Extent Node, requests the exact product year and type!
            funcCall = `${outVar} = arcpy.wfs.PullNLCD(${inVar}, "${outFileName}", year=${p.year}, product="${p.product}")`;
        }
        else if (n.toolId === 'wfs_census') {
            const outFileName = `census_tracts_${n.id.split('_')[1]}.shp`;
            funcCall = `${outVar} = arcpy.wfs.GetCensusTracts(${p.state_fips}, ${p.county_fips}, ${p.year}, "${outFileName}")`;
        }

        // Image Analyst
        else if (n.toolId === 'ia_ndvi') {
            funcCall = `${outVar} = arcpy.ia.NDVI(${inVar}, nir_band_id=${p.nir_band}, red_band_id=${p.red_band})`;
        }
        else if (n.toolId === 'ia_export_dl') {
            funcCall = `${outVar} = arcpy.ia.ExportTrainingDataForDeepLearning(getattr(${inVar}, 'name', ${inVar}), "${p.out_folder}", tile_size_x=${p.tile_size}, tile_size_y=${p.tile_size}, stride_x=${p.stride}, stride_y=${p.stride}, shuffle_chips=${p.shuffle ? 'True' : 'False'})`;
        }

        // GeoAI
        else if (n.toolId === 'ai_detect') {
            funcCall = `${outVar} = arcpy.geoai.DetectObjectsUsingDeepLearning(getattr(${inVar}, 'name', ${inVar}), "${p.out_shp}", "${p.model}")`;
        }
        else if (n.toolId === 'ai_classify') {
            funcCall = `${outVar} = arcpy.geoai.ClassifyPixelsUsingDeepLearning(getattr(${inVar}, 'name', ${inVar}), "${p.out_raster}", "${p.model}")`;
        }

        // Data Management
        else if (n.toolId === 'mgt_clip') {
            const outFileName = `aoi_clip_${n.id.split('_')[1]}.tif`;
            funcCall = `extent_poly = arcpy.Extent(${p.xmin}, ${p.ymin}, ${p.xmax}, ${p.ymax})\n${outVar} = arcpy.management.Clip(${inVar}, extent_poly, "${outFileName}")`;
        }
        else if (n.toolId === 'mgt_buffer') {
            funcCall = `${outVar} = arcpy.analysis.Buffer(${inVar}, "out_buf.shp", "${p.distance} ${p.unit || ''}".strip())`;
        }
        else if (n.toolId === 'mgt_pyramids') {
            funcCall = `arcpy.management.BuildPyramidsAndStats(${inVar}, build_pyramids=${p.build_pyramids ? 'True' : 'False'}, calculate_stats=${p.calculate_stats ? 'True' : 'False'})`;
        }
        
        else {
            funcCall = `# Execute ${n.name}`;
        }
        
        if(funcCall) script += `${funcCall}\n`;
    });
    
    if (processingScope === "Apache Airflow") {
        const indentedScript = script.split('\n').map(line => '        ' + line).join('\n');
        script = `from airflow.decorators import dag, task\nfrom datetime import datetime\n\n@dag(start_date=datetime(2026, 1, 1), schedule=None)\ndef magpi_pipeline():\n    @task\n    def run_magpi():\n${indentedScript}\n\n    run_magpi()\nmagpi_pipeline()`;
    }
    
    return script;
};